#!/usr/bin/env bash
# Write Formula/snetwork.rb into a Homebrew tap from a published release.
# Usage: packaging/update-formula.sh <tap-dir> [tag]   (default: latest release)
# Example: packaging/update-formula.sh ~/projects/homebrew-tap v0.1.0
#
# The same approach as the tap's scripts/update-formula.sh for shist: the
# formula installs the release's prebuilt archives and checks their sums.
set -euo pipefail

REPO="seanmizen/snetwork"
TAP="${1:?usage: $0 <tap-dir> [tag]}"
TAG="${2:-}"
[ -n "$TAG" ] || TAG="$(gh release view -R "$REPO" --json tagName --jq .tagName)"
VER="${TAG#v}"

SUMS="$(gh release download "$TAG" -R "$REPO" -p checksums.txt -O -)"

sum() { # sum <os>_<arch>
  awk -v f="snetwork_${VER}_$1.tar.gz" '$2 == f { print $1 }' <<<"$SUMS"
}
url() { echo "https://github.com/$REPO/releases/download/$TAG/snetwork_${VER}_$1.tar.gz"; }

for t in darwin_arm64 darwin_amd64 linux_arm64 linux_amd64; do
  [ -n "$(sum "$t")" ] || { echo "missing checksum for $t in $TAG" >&2; exit 1; }
done

mkdir -p "$TAP/Formula"
cat > "$TAP/Formula/snetwork.rb" <<RB
# Generated by snetwork's packaging/update-formula.sh - do not edit by hand.
class Snetwork < Formula
  desc "Sean's Network Tool: where am I on the network, at a glance"
  homepage "https://github.com/$REPO"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url darwin_arm64)"
      sha256 "$(sum darwin_arm64)"
    end
    on_intel do
      url "$(url darwin_amd64)"
      sha256 "$(sum darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux_arm64)"
      sha256 "$(sum linux_arm64)"
    end
    on_intel do
      url "$(url linux_amd64)"
      sha256 "$(sum linux_amd64)"
    end
  end

  def install
    bin.install "snetwork"
  end

  test do
    assert_match "snetwork #{version}", shell_output("#{bin}/snetwork -v")
  end
end
RB

echo "wrote $TAP/Formula/snetwork.rb for $TAG"
